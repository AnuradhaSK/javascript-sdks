import {ConfigurationActor, ConfigurationValueReference} from './configuration';

/**
 * A registered gateway.
 */
export interface Gateway {
  baseUrl?: string;
  caCertificate?: string;
  createdAt?: string;
  id?: string;
  isDefault?: boolean;
  name?: string;
  updatedAt?: string;
}

/**
 * A newly registered gateway with its key. The key is returned only here.
 */
export interface GatewayRegistration extends Gateway {
  key: string;
}

/**
 * The payload used to register a gateway.
 */
export interface RegisterGatewayRequest {
  baseUrl: string;
  caCertificate?: string;
  isDefault?: boolean;
  /**
   * The gateway's key. Generated by the server when omitted.
   */
  key?: string;
  name: string;
}

/**
 * The payload used to change a gateway.
 */
export interface UpdateGatewayRequest {
  baseUrl?: string;
  caCertificate?: string;
  key?: string;
  name?: string;
}

/**
 * One resource that differs between two configuration versions.
 */
export interface GatewayConfigurationChange {
  change?: 'added' | 'updated' | 'deleted' | 'unchanged';
  excluded?: boolean;
  id?: string;
  key?: string;
  lines?: {kind?: ' ' | '+' | '-'; text?: string}[];
  name?: string;
  resourceType?: string;
  skipped?: boolean;
}

/**
 * The difference between a configuration version and what a gateway holds.
 */
export interface GatewayConfigurationDiff {
  changes?: GatewayConfigurationChange[];
  fromVersion?: string;
  misplacedSecrets?: ConfigurationValueReference[];
  summary?: {added?: number; deleted?: number; unchanged?: number; updated?: number};
  toVersion?: string;
}

/**
 * The payload used to apply a configuration version to a gateway.
 */
export interface ApplyGatewayConfigurationRequest {
  confirmRemovals?: boolean;
  dryRun?: boolean;
  selection?: string[];
  skip?: string[];
  /**
   * The version to apply. Defaults to the latest.
   */
  version?: string;
}

/**
 * The payload used to revert a gateway to the version it held before.
 */
export interface RevertGatewayConfigurationRequest {
  confirmRemovals?: boolean;
  dryRun?: boolean;
}

/**
 * The variables and secrets an apply found missing or changed.
 */
export interface GatewayValueChanges {
  references?: ConfigurationValueReference[];
  secrets?: string[];
  variables?: string[];
}

/**
 * The outcome of applying or reverting a gateway's configuration.
 */
export interface GatewayApplyResult {
  changed?: GatewayValueChanges;
  diff?: GatewayConfigurationDiff;
  dryRun?: boolean;
  gatewayId?: string;
  /**
   * The gateway's own account of the import.
   */
  import?: Record<string, unknown>;
  missing?: GatewayValueChanges;
  queued?: boolean;
  queuedVersion?: string;
  recorded?: boolean;
}

/**
 * The configuration version a gateway holds.
 */
export interface GatewayAppliedVersion {
  appliedAt?: string;
  appliedBy?: ConfigurationActor;
  appliedVersion?: string;
  gatewayId?: string;
  previousVersion?: string;
}

/**
 * The configuration a gateway runs.
 */
export interface GatewayAppliedConfiguration {
  appliedAt?: string;
  gatewayId: string;
  resources: {id: string; parts?: Record<string, unknown>; resource: Record<string, unknown>; resourceType: string}[];
  skipped?: {code: string; id?: string; reason: string; resourceType: string}[];
  version?: string;
}
